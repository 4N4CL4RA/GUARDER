import { supabase } from '../lib/supabaseClient'

// Função para criar/alterar a tabela reviews
export async function setupReviewsTable() {
  try {
    console.log('🔧 Configurando tabela reviews...')

    // SQL para criar a tabela
    const createTableSQL = `
      create table if not exists public.reviews (
        id bigint generated by default as identity primary key,
        user_id uuid,             -- opcional: id do usuário
        rating smallint not null, -- por exemplo: 1..5 (1 = muito inseguro, 5 = muito seguro)
        comment text,
        lat numeric(9,6) not null,
        lng numeric(9,6) not null,
        created_at timestamptz default now()
      );
    `

    // Executar criação da tabela
    const { error: createError } = await supabase.rpc('exec_sql', { 
      sql: createTableSQL 
    })

    if (createError) {
      console.error('❌ Erro ao criar tabela:', createError)
      return false
    }

    // SQL para configurar RLS
    const rlsSQL = `
      alter table public.reviews enable row level security;
      
      -- Política para leitura pública
      create policy if not exists "Reviews são públicos para leitura" 
        on public.reviews for select 
        using (true);

      -- Política para inserção autenticada
      create policy if not exists "Usuários autenticados podem inserir reviews" 
        on public.reviews for insert 
        with check (auth.uid() is not null);

      -- Política para atualização própria
      create policy if not exists "Usuários podem atualizar próprios reviews" 
        on public.reviews for update 
        using (auth.uid() = user_id);

      -- Política para deleção própria
      create policy if not exists "Usuários podem deletar próprios reviews" 
        on public.reviews for delete 
        using (auth.uid() = user_id);
    `

    const { error: rlsError } = await supabase.rpc('exec_sql', { 
      sql: rlsSQL 
    })

    if (rlsError) {
      console.warn('⚠️ Aviso ao configurar RLS:', rlsError)
    }

    console.log('✅ Tabela reviews configurada com sucesso!')
    return true

  } catch (error) {
    console.error('❌ Erro na configuração da tabela reviews:', error)
    return false
  }
}

