// Função para obter estatísticas da tabela
export async function getReviewsStats() {
  try {
    const { count, error } = await supabase
      .from('reviews')
      .select('*', { count: 'exact', head: true })

    if (error) {
      console.error('❌ Erro ao obter estatísticas:', error)
      return null
    }

    const { data: ratingStats, error: statsError } = await supabase
      .from('reviews')
      .select('rating')

    if (statsError) {
      console.error('❌ Erro ao calcular estatísticas:', statsError)
      return { total: count }
    }

    const ratings = ratingStats?.map(r => r.rating) || []
    const avgRating = ratings.length > 0 
      ? ratings.reduce((a, b) => a + b, 0) / ratings.length 
      : 0

    return {
      total: count || 0,
      averageRating: Number(avgRating.toFixed(1)),
      ratingDistribution: {
        1: ratings.filter(r => r === 1).length,
        2: ratings.filter(r => r === 2).length,
        3: ratings.filter(r => r === 3).length,
        4: ratings.filter(r => r === 4).length,
        5: ratings.filter(r => r === 5).length,
      }
    }

  } catch (error) {
    console.error('❌ Erro ao obter estatísticas:', error)
    return null
  }
}