-- Verificar se tudo foi criado corretamente
SELECT 
  'reviews' AS table_name,
  COUNT(*) AS total_records,
  ROUND(AVG(rating), 2) AS average_rating,
  MIN(created_at) AS oldest_review,
  MAX(created_at) AS newest_review
FROM public.reviews;