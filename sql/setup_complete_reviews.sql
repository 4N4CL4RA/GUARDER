-- Execute este SQL no Console SQL do Supabase para configurar o sistema de reviews

-- Criar tabela reviews
CREATE TABLE IF NOT EXISTS public.reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID,             -- opcional: id do usuário
  rating SMALLINT NOT NULL CHECK (rating >= 1 AND rating <= 5), -- 1-5 (1 = muito inseguro, 5 = muito seguro)
  comment TEXT,
  lat NUMERIC(9,6) NOT NULL,
  lng NUMERIC(9,6) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Habilitar Row Level Security
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;

-- Política para leitura pública
CREATE POLICY IF NOT EXISTS "Reviews são públicos para leitura" 
  ON public.reviews FOR SELECT 
  USING (true);

-- Política para inserção (qualquer pessoa pode inserir - remover auth.uid() is not null se quiser permitir anônimos)
CREATE POLICY IF NOT EXISTS "Qualquer pessoa pode inserir reviews" 
  ON public.reviews FOR INSERT 
  WITH CHECK (true);

-- Política para atualização própria (só funciona se user_id for preenchido)
CREATE POLICY IF NOT EXISTS "Usuários podem atualizar próprios reviews" 
  ON public.reviews FOR UPDATE 
  USING (auth.uid() = user_id OR user_id IS NULL);

-- Política para deleção própria (só funciona se user_id for preenchido)
CREATE POLICY IF NOT EXISTS "Usuários podem deletar próprios reviews" 
  ON public.reviews FOR DELETE 
  USING (auth.uid() = user_id OR user_id IS NULL);

-- Índice para melhorar performance em queries geográficas
CREATE INDEX IF NOT EXISTS reviews_location_idx ON public.reviews (lat, lng);

-- Índice para ordenação por data
CREATE INDEX IF NOT EXISTS reviews_created_at_idx ON public.reviews (created_at DESC);

